// THE CHART. A branching map of the water, read from the bottom up.
//
// The old map was three islands on the horizon and you picked one. That is a choice, but it is
// the SAME choice fourteen times: three cards, one of them is the dangerous one, sail. There
// is no route, so there is nothing to plan and nothing to regret -- and a run-based game whose
// map has no shape is a run-based game whose runs are all the same shape.
//
// So: a lattice. Rows of stops going away from you, edges between them, and you may only ever
// move UP and to an ADJACENT column. Which means the interesting decision is not "which of
// these three" but "which of these three, given the four rows behind it" -- you take the safe
// stop now because the only path to the shop goes through the elite two rows up, and you
// cannot come back for it.
//
// WHAT MAKES A LATTICE WORK, and all three of these are load-bearing:
//
//   EVERY NODE IS REACHABLE AND EVERY NODE LEADS ON. A stop with no way in is scenery and a
//   stop with no way out is a trap; both are generated by accident by any naive edge roll, and
//   both are fixed here rather than being drawn round.
//
//   EDGES NEVER CROSS. If A is left of B in one row and their targets are the other way round
//   in the next, the two lines cross and the player cannot tell which one they are on. Two
//   lines that swap over is not a hard read, it is an unreadable one.
//
//   THE LAST TWO ROWS ARE FIXED. The row below the boss is always a rest, because arriving at
//   a boss with no chance to spend or mend is a coin flip rather than a fight, and the first
//   row is always an ordinary landing, because the first thing a run should teach is the verb.
//
// Nothing here draws and nothing here knows about the voyage. It is a graph with labels.

